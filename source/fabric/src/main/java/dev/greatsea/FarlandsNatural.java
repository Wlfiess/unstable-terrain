package dev.greatsea;
/** Seeded classic density and source-guided natural island fields. */
final class FarlandsNatural {
    private static final class Column {long seed=Long.MIN_VALUE;int x=Integer.MIN_VALUE,z;FarlandsTerrain.Stage stage;final byte[] blocks=new byte[384];}
    private static final ThreadLocal<Column> CACHE=ThreadLocal.withInitial(Column::new);
    static int material(long seed,int x,int y,int z) {
        return material(seed,x,y,z,FarlandsTerrain.stage(x,z));
    }
    static int material(long seed,int x,int y,int z,FarlandsTerrain.Stage stage) {
        if(y< -64 || y>319)return 0;
        var c=CACHE.get();if(c.seed!=seed || c.x!=x || c.z!=z || c.stage!=stage){c.seed=seed;c.x=x;c.z=z;c.stage=stage;build(c,seed,x,z);}
        return c.blocks[y+64]&255;
    }
    private static void build(Column c,long seed,int x,int z) {
        java.util.Arrays.fill(c.blocks,(byte)0);
        var stage=c.stage;var p=FarlandsWorld.project(x,z);
        int a=p.depth(),b=p.tangent();
        if(stage==FarlandsTerrain.Stage.CHUNKS){chunk(c,seed,x,z);return;}
        boolean floating=stage==FarlandsTerrain.Stage.FLOATING;
        boolean sand=stage==FarlandsTerrain.Stage.SAND_FARLANDS;
        if(floating) {
            for(int y=-64;y<=319;y++)c.blocks[y+64]=(byte)FarlandsFloating.material(seed,a,y,b);
        }else {
        // One cross-section controls the wall and its roof. Long openings continue
        // into irregular parallel roof strips; there is no separate periodic cap.
        boolean traced=stage==FarlandsTerrain.Stage.PLAINS || stage==FarlandsTerrain.Stage.ORBITALS || stage==FarlandsTerrain.Stage.CORRUPTED || sand;
        if(traced) {
            for(int y=-64;y<=255;y++)c.blocks[y+64]=(byte)(stage==FarlandsTerrain.Stage.ORBITALS?PlainsFarlandsProfile.orbitalMaterial(seed,a,y,b):PlainsFarlandsProfile.material(seed,a,y,b));
        }else {
        int sampleStep=traced?1:4;
        double[] density=new double[384/sampleStep+1];
        for(int i=0;i<density.length;i++) {
            double y=-64+i*sampleStep;
            density[i]=traced ? PlainsFarlandsProfile.density(seed,a,y,b,classicDensity(seed,a,y,b)) : classicDensity(seed,a,y,b);
        }
        for(int y=-64;y<=319;y++) {
            if(!floating && y>255)continue;
            int i=(y+64)/sampleStep;double d=SeaTerrain.lerp(density[i],density[Math.min(density.length-1,i+1)],Math.floorMod(y+64,sampleStep)/(double)sampleStep);
            if((!floating && y<=-60) || d>0)c.blocks[y+64]=1;
        }
        }
        }
        int skin=floating?FarlandsBiomes.skin(seed,x,z):4;
        for(int y=319;y>=-64;y--) {
            if(c.blocks[y+64]==0 || c.blocks[y+64]==8 || c.blocks[y+64]==29)continue;
            boolean surface=y==319 || c.blocks[y+65]==0;
            if(surface) {
                c.blocks[y+64]=(byte)(sand?5:skin);
                for(int k=1;k<=3 && y-k>=-64 && c.blocks[y-k+64]!=0 && c.blocks[y-k+64]!=8 && c.blocks[y-k+64]!=29;k++)c.blocks[y-k+64]=(byte)(sand?6:skin==5?6:skin==37?37:3);
            }else if(sand)c.blocks[y+64]=6;
        }
        // Floating structures are generated by Minecraft's native structure pipeline.
        // Do not turn the old downloaded mineshaft outline into stamped terrain.
    }
    private static void chunk(Column c,long seed,int x,int z) {
        int cx=Math.floorDiv(x,16),cz=Math.floorDiv(z,16),lx=Math.floorMod(x,16),lz=Math.floorMod(z,16);
        long h=SeaTerrain.hash(seed+856,cx,cz);int kind=FarlandsTerrain.chunkBiome(seed,x,z);
        int top=RandomChunkReference.height(seed,x,z);
        int skin=FarlandsBiomes.skin(seed,x,z);
        for(int y=-64;y<=top;y++) {
            int m=y<=-60?8:y==-59?10:y==top?skin:y>top-4?(skin==5?6:skin==37?37:3):y<0?2:1;
            if(kind==10 && y>top-65 && y<top-3)m=37;
            if(kind==12 && y>top-45 && y<top && Math.hypot(lx-8,lz-8)<6)m=40;
            c.blocks[y+64]=(byte)m;
        }
    }
    /** Long continuous galleries: cross-section noise stretches into the wall instead
     * of cutting short rounded pockets independently at every few depth blocks. */
    static double classicDensity(long seed,double depth,double y,double tangent) {
        double drift=.18*SeaTerrain.noise(seed+8541,1024,tangent,1400);
        double z=tangent/8.5+drift, v=y/6.8;
        return .08+gradient2(seed+854,z,v)+.32*gradient2(seed+855,z*2,v*2)
                +.10*gradient2(seed+856,z*4,v*4)
                +.018*noise3(seed+8542,1024/640.0,y/24.0,tangent/36.0);
    }
    static double gradient2(long seed,double x,double y) {
        long ix=(long)Math.floor(x),iy=(long)Math.floor(y);double u=x-ix,v=y-iy;
        return 1.7*SeaTerrain.lerp(SeaTerrain.lerp(dot(seed,ix,iy,u,v),dot(seed,ix+1,iy,u-1,v),SeaTerrain.smooth(u)),
                SeaTerrain.lerp(dot(seed,ix,iy+1,u,v-1),dot(seed,ix+1,iy+1,u-1,v-1),SeaTerrain.smooth(u)),SeaTerrain.smooth(v));
    }
    private static double dot(long seed,long x,long y,double u,double v) {
        return switch((int)(SeaTerrain.hash(seed,x,y)&7)) {
            case 0 -> u;case 1 -> -u;case 2 -> v;case 3 -> -v;
            case 4 -> (u+v)*.70710678;case 5 -> (u-v)*.70710678;
            case 6 -> (-u+v)*.70710678;default -> (-u-v)*.70710678;
        };
    }
    static double noise3(long seed,double x,double y,double z) {
        long ix=(long)Math.floor(x),iy=(long)Math.floor(y),iz=(long)Math.floor(z);double u=SeaTerrain.smooth(x-ix),v=SeaTerrain.smooth(y-iy),w=SeaTerrain.smooth(z-iz);
        double[] plane=new double[2];
        for(int k=0;k<2;k++) {
            double a=SeaTerrain.lerp(value(seed,ix,iy,iz+k),value(seed,ix+1,iy,iz+k),u);
            double b=SeaTerrain.lerp(value(seed,ix,iy+1,iz+k),value(seed,ix+1,iy+1,iz+k),u);plane[k]=SeaTerrain.lerp(a,b,v);
        }
        return SeaTerrain.lerp(plane[0],plane[1],w);
    }
    private static double value(long seed,long x,long y,long z){return SeaTerrain.unit(SeaTerrain.hash(seed+y*0x632BE59BD9B4E019L,x,z))*2-1;}
}


